# \x07 star, \x08 clock, \x0e down-triangle
# \x01 = A button, \x02 = B button, \x03 = D-pad, \x04 = "ST" (start) pill
# \x05, \x06 = theme symbols (generated per theme)


def parse():
    glyphs = {}
    cur = None
    rows = []
    for line in RAW.strip("\n").split("\n"):
        if line.startswith("@"):
            if cur is not None:
                glyphs[cur] = rows
            name = line[1:]
            if name == "SPACE":
                cur = " "
            elif name.startswith("\\x"):
                cur = chr(int(name[2:], 16))
            else:
                cur = name
            rows = []
        else:
            rows.append(line)
    glyphs[cur] = rows
    out = {}
    for ch, rows in glyphs.items():
        w = max(len(r) for r in rows)
        bits = []
        for y in range(9):
            r = rows[y] if y < len(rows) else ""
            v = 0
            for x, c in enumerate(r):
                if c == "#":
                    v |= 0x80 >> x
            bits.append(v)
        out[ch] = (w, bits)
    return out


GLYPHS = parse()


def glyph(ch):
    return GLYPHS.get(ch, GLYPHS["?"])


def text_width(s, bold=False):
    w = 0
    for ch in s:
        gw, _ = glyph(ch)
        w += gw + 1 + (1 if bold else 0)
    return max(0, w - 1)


def draw_text(img, x, y, s, color=3, bold=False):
    """img: 2D list [y][x] of color ints."""
    for ch in s:
        gw, bits = glyph(ch)
        for dy in range(9):
            b = bits[dy]
            for dx in range(8):
                if b & (0x80 >> dx):
                    for bx in ((0, 1) if bold else (0,)):
                        px, py = x + dx + bx, y + dy
                        if 0 <= py < len(img) and 0 <= px < len(img[0]):
                            img[py][px] = color
        x += gw + 1 + (1 if bold else 0)
    return x
